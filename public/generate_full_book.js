const chapters = [];
for (const section of detailRoot.section.detail) {
  for (const group of section.chapterGroup.detail) {
    for (const chapter of group.chapters.detail) {
      chapters.push({
        number: chapter.number,
        name: chapterTitlesTa[chapter.number] || chapter.name,         // Tamil chapter title
        translation: chapterTitlesEn[chapter.number] || chapter.translation, // English chapter title
        deTitle: chapterTitlesDe[chapter.number] || chapterTitlesEn[chapter.number], // German chapter title (falls back to EN)
        transliteration: chapter.transliteration,
        start: chapter.start,
        end: chapter.end,
        section: sectionTitlesTa[section.number] || section.name,              // Tamil section title
        sectionTranslation: sectionTitlesEn[section.number] || section.translation, // English section
        sectionTranslationDe: sectionTitlesDe[section.number] || sectionTitlesEn[section.number], // German section
        group: groupTitlesTa[group.number] || group.name,              // Tamil group title
        groupTranslation: groupTitlesEn[group.number] || group.translation, // English group
        groupTranslationDe: groupTitlesDe[group.number] || groupTitlesEn[group.number], // German group
        kurals: sourceKurals.slice(chapter.start - 1, chapter.end)
      });
    }
  }
}

